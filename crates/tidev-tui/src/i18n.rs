/// Locale-aware access to embedded TUI translations.
#[derive(Clone, Debug)]
pub(crate) struct UiText {
    locale: LanguageIdentifier,
}

impl UiText {
    pub(crate) fn from_preference(preference: &str) -> Self {
        let system_locale = system_locale();
        let locale = match preference {
            "zh-CN" => SIMPLIFIED_CHINESE,
            "en-US" => DEFAULT_LOCALE,
            _ => system_locale.as_deref().unwrap_or(DEFAULT_LOCALE),
        };
        let locale = locale
            .parse::<LanguageIdentifier>()
            .unwrap_or_else(|_| DEFAULT_LOCALE.parse().expect("valid default locale"));
        Self { locale }
    }

    pub(crate) fn text(&self, key: TextKey) -> String {
        LOCALES.lookup(&self.locale, key.id())
    }

    pub(crate) fn cache_key(&self) -> String {
        self.locale.to_string()
    }

    pub(crate) fn text_with_count(&self, key: TextKey, count: usize) -> String {
        let mut args = HashMap::new();
        args.insert(Cow::Borrowed("count"), FluentValue::from(count as i64));
        clean_fluent_text(LOCALES.lookup_with_args(&self.locale, key.id(), &args))
    }

    pub(crate) fn text_with_value(&self, key: TextKey, name: &str, value: &str) -> String {
        let mut args = HashMap::new();
        args.insert(
            Cow::Owned(name.to_string()),
            FluentValue::from(value.to_string()),
        );
        clean_fluent_text(LOCALES.lookup_with_args(&self.locale, key.id(), &args))
    }

    pub(crate) fn text_with_values(&self, key: TextKey, values: &[(&str, &str)]) -> String {
        let mut args = HashMap::new();
        for (name, value) in values {
            args.insert(
                Cow::Owned((*name).to_string()),
                FluentValue::from((*value).to_string()),
            );
        }
        clean_fluent_text(LOCALES.lookup_with_args(&self.locale, key.id(), &args))
    }
}

fn clean_fluent_text(text: String) -> String {
    text.replace(['\u{2068}', '\u{2069}'], "")
}

pub(crate) fn mode_title(ui_text: &UiText, mode: tidev_core::Mode) -> String {
    match mode {
        tidev_core::Mode::Build => ui_text.text(TextKey::Build),
        tidev_core::Mode::Plan => ui_text.text(TextKey::Plan),
    }
}

pub(crate) fn thinking_level_name(ui_text: &UiText, name: &str) -> String {
    let key = match name {
        "Off" => Some(TextKey::LevelOff),
        "On" => Some(TextKey::LevelOn),
        "Minimal" => Some(TextKey::LevelMinimal),
        "Low" => Some(TextKey::LevelLow),
        "Medium" => Some(TextKey::LevelMedium),
        "High" => Some(TextKey::LevelHigh),
        "XHigh" => Some(TextKey::LevelXHigh),
        "Max" => Some(TextKey::LevelMax),
        _ => None,
    };
    key.map(|key| ui_text.text(key))
        .unwrap_or_else(|| name.to_string())
}

pub(crate) fn agent_type_name(
    ui_text: &UiText,
    agent_type: tidev_core::agent_type::AgentType,
) -> String {
    let key = match agent_type {
        tidev_core::agent_type::AgentType::General => TextKey::AgentGeneralName,
        tidev_core::agent_type::AgentType::Explorer => TextKey::AgentExplorerName,
        tidev_core::agent_type::AgentType::Librarian => TextKey::AgentLibrarianName,
        tidev_core::agent_type::AgentType::Oracle => TextKey::AgentOracleName,
        tidev_core::agent_type::AgentType::Fixer => TextKey::AgentFixerName,
    };
    ui_text.text(key)
}

pub(crate) fn agent_type_name_from_str(ui_text: &UiText, name: &str) -> String {
    let key = match name {
        "general" => Some(TextKey::AgentGeneralName),
        "explorer" => Some(TextKey::AgentExplorerName),
        "librarian" => Some(TextKey::AgentLibrarianName),
        "oracle" => Some(TextKey::AgentOracleName),
        "fixer" => Some(TextKey::AgentFixerName),
        _ => None,
    };
    key.map(|key| ui_text.text(key))
        .unwrap_or_else(|| name.to_string())
}

fn system_locale() -> Option<String> {
    sys_locale::get_locale().map(|locale| {
        if locale.eq_ignore_ascii_case("zh") || locale.to_ascii_lowercase().starts_with("zh-") {
            SIMPLIFIED_CHINESE.to_owned()
        } else {
            DEFAULT_LOCALE.to_owned()
        }
    })
}
